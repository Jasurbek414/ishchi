/// Ray-casting test to determine if [point] is inside any polygon ring of a region.
bool _isPointInPoly(LatLng point, List<LatLng> polygon) {
  bool inside = false;
  for (int i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    final xi = polygon[i].longitude, yi = polygon[i].latitude;
    final xj = polygon[j].longitude, yj = polygon[j].latitude;
    final intersect = ((yi > point.latitude) != (yj > point.latitude)) &&
        (point.longitude < (xj - xi) * (point.latitude - yi) / (yj - yi) + xi);
    if (intersect) inside = !inside;
  }
  return inside;
}

/// Returns the [UzbekistanRegionGeo] whose administrative polygon covers [point], or null.
UzbekistanRegionGeo? findRegionAtPoint(LatLng point) {
  for (final region in uzbekistanRegionsGeo) {
    for (final ring in region.polygons) {
      if (_isPointInPoly(point, ring)) return region;
    }
  }
  return null;
}
